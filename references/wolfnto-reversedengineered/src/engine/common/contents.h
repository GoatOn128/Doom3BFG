#pragma once

#include <cstdint>

// Shared retail contents mask.  The collision and renderer declarations use
// the same global constants in the shipping code; keeping one definition
// avoids include-order-dependent values.
enum contentsFlags_t : std::uint32_t {
  CONTENTS_SOLID = 0x00000001u,
  CONTENTS_OPAQUE = 0x00000002u,
  CONTENTS_WATER = 0x00000004u,
  CONTENTS_PLAYERCLIP = 0x00000008u,
  CONTENTS_MONSTERCLIP = 0x00000010u,
  CONTENTS_VEHICLECLIP = 0x00000020u,
  CONTENTS_MOVEABLECLIP = 0x00000040u,
  CONTENTS_SHOTCLIP = 0x00000080u,
  CONTENTS_IKCLIP = 0x00000100u,
  CONTENTS_AIAWARE = 0x00000200u,
  CONTENTS_AI = 0x00000400u,
  CONTENTS_PROJECTILE = 0x00000800u,
  CONTENTS_CORPSE = 0x00001000u,
  CONTENTS_BREAKABLE = 0x00002000u,
  CONTENTS_TRIGGER = 0x00004000u,
  CONTENTS_PLAYER = 0x00008000u,
  CONTENTS_VEHICLE = 0x00010000u,
  CONTENTS_OBSTACLE = 0x00020000u,
  CONTENTS_UNUSED_BIT_18 = 0x00040000u,
  CONTENTS_PLAYERCOVERCLIP = 0x00080000u,
  CONTENTS_MONSTERCOVERCLIP = 0x00100000u,
  CONTENTS_PLAYERFOCUS = 0x00200000u,
  CONTENTS_PUSHABLE = 0x00400000u,
  CONTENTS_SHIELD = 0x00800000u,
  CONTENTS_UNUSED_BIT_24 = 0x01000000u,
  CONTENTS_AAS_FLY = 0x02000000u,
  CONTENTS_AAS_SOLID = 0x04000000u,
  CONTENTS_AAS_OBSTACLE = 0x08000000u,
  CONTENTS_AAS_CLUSTER_PORTAL = 0x10000000u,
  CONTENTS_AAS_WALKABLE_WALL = 0x20000000u,
  CONTENTS_NOCOVER = 0x40000000u,
  CONTENTS_DO_NOT_USE = 0x80000000u,
  CONTENTS_NONE = 0,
  CONTENTS_ALL = 0xFFFFFFFFu,

  // Collision-model callers historically used BODY as their aggregate
  // dynamic-body mask.  Retail does not assign it an independent bit.
  CONTENTS_BODY = CONTENTS_PLAYER | CONTENTS_CORPSE,
};

using cmContents_t = contentsFlags_t;
