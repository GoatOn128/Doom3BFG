void idBareDCTHuffmanTable::Init(const std::uint8_t* bits,
                                 const std::uint8_t* values, bool encode) {
  std::memmove(symbols, values, sizeof(symbols));

  std::uint8_t huffSize[272];
  unsigned int huffCode[260];
  int symbolCount = 0;
  for (int length = 1; length <= 16; ++length) {
    if (bits[length] != 0) {
      std::memset(huffSize + symbolCount, length, bits[length]);
      symbolCount += bits[length];
    }
  }
  huffSize[symbolCount] = 0;

  unsigned int nextCode = 0;
  int sizeIndex = 0;
  int currentSize = huffSize[0];
  while (huffSize[sizeIndex] != 0) {
    while (huffSize[sizeIndex] == currentSize)
      huffCode[sizeIndex++] = nextCode++;
    nextCode <<= 1;
    ++currentSize;
  }

  minCode[0] = 0;
  maxCode[0] = 0;
  int firstSymbol = 0;
  for (int length = 1; length <= 16; ++length) {
    if (bits[length] != 0) {
      symOffset[length] = firstSymbol;
      minCode[length] = static_cast<int>(huffCode[firstSymbol]);
      firstSymbol += bits[length];
      maxCode[length] = static_cast<int>(huffCode[firstSymbol - 1]);
    } else {
      symOffset[length] = 0;
      minCode[length] = -1;
      maxCode[length] = -1;
    }
  }
  maxCode[17] = 0xFFFFF;

  std::memset(look_nbits, 0, sizeof(look_nbits));
  std::memset(look_sym, 0, sizeof(look_sym));
  int canonicalIndex = 0;
  for (int length = 1; length <= 8; ++length) {
    for (int indexAtLength = 0; indexAtLength < bits[length];
         ++indexAtLength, ++canonicalIndex) {
      const int replicatedBits = 8 - length;
      const int firstLookup = huffCode[canonicalIndex] << replicatedBits;
      const int lookupCount = 1 << replicatedBits;
      for (int lookup = 0; lookup < lookupCount; ++lookup) {
        look_nbits[firstLookup + lookup] = static_cast<std::uint8_t>(length);
        look_sym[firstLookup + lookup] = values[canonicalIndex];
      }
    }
  }

  std::memset(test_nbits, 0, sizeof(test_nbits));
  canonicalIndex = 0;
  for (int length = 1; length <= 16; ++length) {
    for (int indexAtLength = 0; indexAtLength < bits[length];
         ++indexAtLength, ++canonicalIndex) {
      const int threshold = static_cast<int>(
          (huffCode[canonicalIndex] + 1) << (16 - length));
      for (int testLength = length; testLength < 16; ++testLength)
        test_nbits[testLength] = threshold;
    }
  }

  if (encode) {
    std::memset(code, 0, sizeof(code));
    std::memset(size, 0, sizeof(size));
    for (int index = 0; index < symbolCount; ++index) {
      const std::uint8_t symbol = values[index];
      code[symbol] = huffCode[index];
      size[symbol] = static_cast<char>(huffSize[index]);
    }
  }
}

idBareDCTHuffmanTable::idBareDCTHuffmanTable(huffmanType_t huffmanType,
                                             bool encode) {
  switch (huffmanType) {
    case HUFFMAN_TYPE_Y_DC:
      Init(kRetailHuffmanData + kBitsYDC,
           kRetailHuffmanData + kValuesYDC, encode);
      break;
    case HUFFMAN_TYPE_Y_AC:
      Init(kRetailHuffmanData + kBitsYAC,
           kRetailHuffmanData + kValuesYAC, encode);
      break;
    case HUFFMAN_TYPE_COCG_DC:
      Init(kRetailHuffmanData + kBitsCoCgDC,
           kRetailHuffmanData + kValuesCoCgDC, encode);
      break;
    case HUFFMAN_TYPE_COCG_AC:
      Init(kRetailHuffmanData + kBitsCoCgAC,
           kRetailHuffmanData + kValuesCoCgAC, encode);
      break;
  }
}
